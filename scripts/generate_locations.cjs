rawData.split('\n').forEach(line => {
  line = line.trim();
  if (!line) return;
  
  const poolMatch = line.match(/## POOL \d: ([A-Z_]+)/);
  if (poolMatch) {
    currentPool = poolMatch[1];
    output[currentPool] = [];
    return;
  }
  
  if (currentPool) {
    // Extract the months array first
    const bracketStart = line.lastIndexOf('[');
    const bracketEnd = line.lastIndexOf(']');
    if (bracketStart !== -1 && bracketEnd !== -1) {
      const monthsStr = line.substring(bracketStart + 1, bracketEnd);
      const months = monthsStr.split(',').map(Number);
      
      const rest = line.substring(0, bracketStart).trim();
      // Remove trailing comma if exists
      const cleanRest = rest.endsWith(',') ? rest.slice(0, -1).trim() : rest;
      
      // Now split the rest from the end: lon, lat, country, name
      const parts = cleanRest.split(',');
      if (parts.length >= 4) {
        const lon = parseFloat(parts[parts.length - 1].trim());
        const lat = parseFloat(parts[parts.length - 2].trim());
        const country = parts[parts.length - 3].trim();
        const name = parts.slice(0, parts.length - 3).join(',').trim();
        
        output[currentPool].push({
          name: name,
          country: country,
          lat: lat,
          lon: lon,
          months: months
        });
      }
    }
  }
});

